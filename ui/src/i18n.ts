export function translate(lang: Lang, key: Key, vars: Record<string, string | number> = {}): string {
  const template = STRINGS[lang][key] ?? STRINGS.en[key];
  return template.replace(/\{(\w+)\}/g, (_, name: string) => String(vars[name] ?? `{${name}}`));
}
